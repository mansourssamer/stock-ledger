"""Writes js/schema.js from a fully migrated Stock & Ledger database (erp.db).

    python3 tools/gen_schema.py path/to/erp.db

Every table except the sign-in tables is mirrored. Columns named id or *_id keep no
SQLite type, so imported numbers and new text ids can sit side by side and joins work."""
import json, sqlite3, sys

SKIP = {'users', 'login_failures'}
KEYS = {'currencies': 'code', 'app_settings': 'key'}

def main(path):
    c = sqlite3.connect(path)
    tables = {}
    for (t,) in c.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"):
        if t in SKIP:
            continue
        cols = []
        for r in c.execute(f'PRAGMA table_info("{t}")'):
            name, typ = r[1], (r[2] or '').upper()
            if name == 'id' or name.endswith('_id'):
                typ = ''
            dflt = r[4]
            if dflt is None:
                d = None
            elif "datetime('now')" in dflt:
                d = {'now': 'datetime'}
            elif "date('now')" in dflt:
                d = {'now': 'date'}
            elif dflt.startswith("'"):
                d = dflt.strip("'")
            else:
                try:
                    d = int(dflt)
                except ValueError:
                    d = float(dflt)
            cols.append([name, typ] + ([d] if d is not None else []))
        tables[t] = {'key': KEYS.get(t, 'id'), 'cols': cols}
    # Kept by this app only: the number shown for an order or purchase order made here (the id of
    # the record, which table, its number). Fixed when the record is made, so deleting an earlier
    # one doesn't renumber the rest, and backups give the old app the same numbers.
    tables['ref_numbers'] = {'key': 'id', 'cols': [['id', ''], ['tbl', 'TEXT'], ['number', 'INTEGER']]}
    out = ("// Generated by tools/gen_schema.py from the Stock & Ledger database. Do not edit by hand.\n"
           "// Each table: its key column and [column, SQLite type, default?]. Id columns have no type on purpose.\n"
           "// A default of {now: 'datetime'} or {now: 'date'} means the current UTC time or day.\n"
           "export const TABLES = {\n" + ",\n".join(f"  {json.dumps(t)}: {json.dumps(v, ensure_ascii=False)}" for t, v in tables.items()) + "\n};\n")
    open('js/schema.js', 'w').write(out)
    print(len(tables), 'tables written to js/schema.js')

if __name__ == '__main__':
    main(sys.argv[1])
