"""Writes js/oldschema.js: the old app's table definitions, so a backup made by the new app is a
database the old app opens (and its Backup page restores).   python3 tools/gen_oldschema.py erp.db"""
import json, sqlite3, sys
c = sqlite3.connect(sys.argv[1])
ddl = [r[0] for r in c.execute("SELECT sql FROM sqlite_master WHERE type IN ('table', 'index', 'trigger', 'view') AND sql IS NOT NULL "
                               "AND name NOT LIKE 'sqlite_%' ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, name")]
out = ("// Generated by tools/gen_oldschema.py from the old app's database. Do not edit by hand.\n"
       "// The old app's tables, exactly: a backup from this app is a database the old app can open.\n"
       f"export const OLD_SCHEMA = {json.dumps(ddl, ensure_ascii=False, indent=1)};\n")
open('js/oldschema.js', 'w').write(out)
print(len(ddl), 'statements')
